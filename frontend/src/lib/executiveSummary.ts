import type { DocumentDetail, RiskFindingRead } from "@/lib/types"

const SEVERITY_ORDER = ["CRITICAL", "HIGH", "MEDIUM", "LOW"] as const

function uniqueTitles(findings: RiskFindingRead[], severities: string[]): string[] {
  const titles: string[] = []
  for (const finding of findings) {
    if (!severities.includes(finding.severity)) continue
    if (!finding.title) continue
    if (!titles.includes(finding.title)) titles.push(finding.title)
  }
  return titles
}

function joinNames(names: string[]): string {
  if (names.length <= 1) return names[0] ?? "the flagged clause(s)"
  return `${names.slice(0, -1).join(", ")} and ${names[names.length - 1]}`
}

/** One-line, plain-English consequence framing for a severity level. */
export function severityImpactText(severity: string): string {
  const impact: Record<string, string> = {
    CRITICAL:
      "Can create large, open-ended financial or legal exposure. Treat this as a must-review before signing.",
    HIGH: "May shift material risk or cost onto you. Worth negotiating before signing.",
    MEDIUM: "May add obligations or inconvenience over time. Clarify the wording.",
    LOW: "Usually routine, but confirm the wording is fair and balanced.",
  }
  return impact[severity] ?? impact.LOW
}

/** Clause reference such as "Clause 3 · p.1". */
export function findingClauseRef(finding: RiskFindingRead): string {
  const parts: string[] = []
  if (finding.clause_number !== null) parts.push(`Clause ${finding.clause_number}`)
  if (finding.clause_page !== null) parts.push(`p.${finding.clause_page}`)
  return parts.join(" · ")
}

/**
 * Deterministic, plain-English executive summary derived from the actual
 * findings. This is not generated by a language model: every sentence is
 * templated around real analyzer output.
 */
export function executiveSummary(doc: DocumentDetail): string[] {
  const findings = [...(doc.analysis?.findings ?? [])]
  const clauseCount = doc.clauses.length

  if (findings.length === 0) {
    return [
      `This automated review looked across ${clauseCount} clause(s) and found nothing to flag.`,
      "That does not mean the contract is legally safe - it means none of the risk patterns this tool checks for were detected.",
      "A lawyer should still review the contract before you sign.",
    ]
  }

  const counts: Record<string, number> = { CRITICAL: 0, HIGH: 0, MEDIUM: 0, LOW: 0 }
  for (const finding of findings) {
    counts[finding.severity] = (counts[finding.severity] ?? 0) + 1
  }

  const paragraphs = [
    `The automated review looked across ${clauseCount} clause(s) and flagged ${findings.length} point(s) to check - ${counts.CRITICAL} critical, ${counts.HIGH} high, ${counts.MEDIUM} medium and ${counts.LOW} low.`,
  ]

  const focus = uniqueTitles(findings, ["CRITICAL", "HIGH"])
  paragraphs.push(
    focus.length > 0
      ? `The main areas to look at are ${joinNames(focus.slice(0, 4))}.`
      : "The points raised are low-to-medium priority, but still worth reading.",
  )

  paragraphs.push(
    "Flagged wording may shift risk, cost or flexibility in ways worth understanding before you sign.",
  )
  paragraphs.push(
    "This tool detects phrasing patterns. It does not judge whether a clause is lawful. Review the flagged points with a lawyer before signing.",
  )
  return paragraphs
}

export function findingsBySeverity(findings: RiskFindingRead[]): RiskFindingRead[] {
  const order = SEVERITY_ORDER as readonly string[]
  return [...findings].sort((a, b) => order.indexOf(a.severity) - order.indexOf(b.severity))
}